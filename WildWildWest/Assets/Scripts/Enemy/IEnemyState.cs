public interface IEnemyState
{
    void Enter();//действия при входе в состояния(возобновить движение врага)
    void Update();//действия, который выполняются каждый кадр, пока состояние актвино(преследовать игрока)
    void Exit();//действия при выходе из состояния(При необходимости завершить действия состояния)
}